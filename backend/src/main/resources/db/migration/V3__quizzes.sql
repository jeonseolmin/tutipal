-- 이해도 확인 질문 (목업 15 · 16 · 22 · 23 · 24). 객관식은 바로 채점, 주관식은 AI 채점 후 선생님이 바꿀 수 있음.
CREATE TABLE quizzes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    session_id     BIGINT        NOT NULL REFERENCES study_sessions (id),
    type           VARCHAR(20)   NOT NULL CHECK (type IN ('CHOICE', 'TEXT')),
    question       VARCHAR(1000) NOT NULL,
    choices        TEXT[],                       -- 객관식 보기 (2~5개)
    answer_index   INTEGER,                      -- 객관식 정답 번호 (0부터)
    model_answer   VARCHAR(2000),                -- 주관식 모범 답안
    closes_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_quizzes_session ON quizzes (session_id);

CREATE TABLE quiz_answers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    quiz_id       BIGINT        NOT NULL REFERENCES quizzes (id),
    user_id       BIGINT        NOT NULL REFERENCES users (id),
    choice_index  INTEGER,
    text          VARCHAR(2000),
    correct       BOOLEAN,                       -- NULL = 채점 전 (AI 채점 중이거나 실패)
    graded_by     VARCHAR(20) CHECK (graded_by IN ('AUTO', 'AI', 'TEACHER')),
    feedback      VARCHAR(500),
    CONSTRAINT uk_quiz_answer UNIQUE (quiz_id, user_id)
);
