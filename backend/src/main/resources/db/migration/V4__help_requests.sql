-- 학생 → 선생님 도움 요청 (목업 17 · 25). 수락되면 1:1 화면공유 방(LiveKit 방 B)이 열린다.
CREATE TABLE help_requests (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    session_id    BIGINT       NOT NULL REFERENCES study_sessions (id),
    user_id       BIGINT       NOT NULL REFERENCES users (id),
    message       VARCHAR(300) NOT NULL,
    share_screen  BOOLEAN      NOT NULL,
    status        VARCHAR(20)  NOT NULL CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'DONE'))
);
-- 한 학생은 한 세션에 열린 요청(대기 · 진행 중)을 하나만
CREATE UNIQUE INDEX uk_help_open ON help_requests (session_id, user_id) WHERE status IN ('PENDING', 'ACCEPTED');
CREATE INDEX idx_help_session ON help_requests (session_id);
