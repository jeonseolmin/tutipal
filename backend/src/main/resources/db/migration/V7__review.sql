ALTER TABLE users ADD COLUMN review_consent BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE review_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    summary       VARCHAR(500) NOT NULL,
    embedding     vector(1024) NOT NULL,
    seen_count    INTEGER      NOT NULL DEFAULT 1,
    seen_seconds  INTEGER      NOT NULL DEFAULT 0,
    first_seen    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_seen     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    suggested_at  TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_review_user ON review_items (user_id, last_seen);
