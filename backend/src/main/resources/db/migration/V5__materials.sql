-- 세션 자료 (목업 28) + RAG 청크. 임베딩은 Ollama bge-m3 (1024차원). 모델을 바꾸면 청크를 다시 만들어야 함.
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE materials (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    session_id    BIGINT       NOT NULL REFERENCES study_sessions (id),
    uploader_id   BIGINT       NOT NULL REFERENCES users (id),
    filename      VARCHAR(200) NOT NULL,
    size_bytes    INTEGER      NOT NULL,
    data          BYTEA        NOT NULL,     -- ponytail: 10MB 이하라 DB 에 그대로. 커지면 파일 저장소로
    status        VARCHAR(20)  NOT NULL CHECK (status IN ('PROCESSING', 'DONE', 'FAILED')),
    chunk_count   INTEGER      NOT NULL DEFAULT 0,
    error         VARCHAR(200)
);
CREATE INDEX idx_materials_session ON materials (session_id);

CREATE TABLE material_chunks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id  BIGINT       NOT NULL REFERENCES materials (id) ON DELETE CASCADE,
    session_id   BIGINT       NOT NULL,
    page         INTEGER,
    content      TEXT         NOT NULL,
    embedding    vector(1024) NOT NULL
);
CREATE INDEX idx_chunks_session ON material_chunks (session_id);
CREATE INDEX idx_chunks_embedding ON material_chunks USING hnsw (embedding vector_cosine_ops);
