-- 단체 학습 세션과 참가자. 선생님/학생은 계정이 아니라 세션마다 (세션 연 사람 = TEACHER).
CREATE TABLE study_sessions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    title            VARCHAR(50)  NOT NULL,
    topic            VARCHAR(20)  NOT NULL,
    invite_code      VARCHAR(6)   NOT NULL UNIQUE,
    owner_id         BIGINT       NOT NULL REFERENCES users (id),
    difficulty       SMALLINT     NOT NULL DEFAULT 3 CHECK (difficulty BETWEEN 1 AND 5),
    hide_answers     BOOLEAN      NOT NULL DEFAULT FALSE,
    prefer_materials BOOLEAN      NOT NULL DEFAULT FALSE,
    ended_at         TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE session_participants (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    session_id  BIGINT      NOT NULL REFERENCES study_sessions (id),
    user_id     BIGINT      NOT NULL REFERENCES users (id),
    role        VARCHAR(20) NOT NULL CHECK (role IN ('TEACHER', 'STUDENT')),
    CONSTRAINT uk_participant UNIQUE (session_id, user_id)
);
CREATE INDEX idx_participants_user ON session_participants (user_id);
